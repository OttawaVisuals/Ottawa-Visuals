"""Generate a local-file fallback from the canonical JSON snapshots."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[1]/'data'
payload={name:json.loads((root/(name+'.json')).read_text(encoding='utf-8')) for name in ['budget','lansdowne','history','kpis','inflation']}
(root/'page-data.js').write_text('// Generated by scripts/package_page_data.py; edit the source JSON/build scripts.\nwindow.OTTAWA_BUDGET_DATA = '+json.dumps(payload,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
print('Packaged budget, project, history, KPI and CPI snapshots for file:// preview.')
