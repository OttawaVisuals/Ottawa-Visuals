"""Build the theme-aware award sprite from the editable individual SVGs.

Run from any directory: python PWHL/scripts/build_award_sprite.py
The dashboard uses the sprite so its manually selected theme controls colours.
Standalone SVGs also support the operating system's preferred colour scheme.
"""

from pathlib import Path
import xml.etree.ElementTree as ET

ICONS = Path(__file__).resolve().parents[1] / "icon-concepts"
NS = "http://www.w3.org/2000/svg"
ET.register_namespace("", NS)


def build():
    sprite = ET.Element(f"{{{NS}}}svg")
    for source in sorted(ICONS.glob("*.svg")):
        if source.name == "awards.svg":
            continue
        original = ET.parse(source).getroot()
        attrs = {key: value for key, value in original.attrib.items()
                 if key not in {"role", "aria-labelledby", "aria-label"}}
        symbol = ET.SubElement(sprite, f"{{{NS}}}symbol", {"id": source.stem, **attrs})
        for child in original:
            # Decorative symbols inherit colour from the host page, not OS theme.
            if child.tag not in {f"{{{NS}}}title", f"{{{NS}}}style"}:
                symbol.append(child)
    ET.indent(sprite, space="  ")
    (ICONS / "awards.svg").write_text(
        '<!-- Generated by scripts/build_award_sprite.py; edit individual SVGs. -->\n'
        + ET.tostring(sprite, encoding="unicode") + "\n", encoding="utf-8")
    print(f"Built {len(sprite)} award symbols")


if __name__ == "__main__":
    build()
